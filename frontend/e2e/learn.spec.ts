test("Text to sign: word cards, fingerspelled cards, replay and clear", async ({ page, errors }) => {
  void errors
  await openApp(page, "learn")
  const input = page.getByLabel("Type a word or sentence")
  await page.getByRole("button", { name: "Show signs" }).click()
  await expect(page.getByText("Type some letters or words first.")).toBeVisible()
  await input.fill("Thank you, Ria! Jo")
  await input.press("Enter")
  const cards = page.getByTestId("sign-cards").getByRole("article")
  await expect(cards).toHaveCount(6)
  await expect(page.getByRole("article", { name: "Sign card THANK YOU" })).toContainText("Flat hand moves down")
  await expect(page.getByRole("article", { name: "Sign card R" })).toBeVisible()
  await expect(page.getByRole("article", { name: "Sign card J" })).toContainText("Motion letter")
  await page.getByRole("button", { name: "Replay THANK YOU" }).click()
  await page.getByRole("button", { name: "Replay R" }).click()
  await page.getByRole("button", { name: "Clear" }).click()
  await expect(page.getByTestId("sign-cards")).toHaveCount(0)
  await expect(input).toHaveValue("")
})
