import { expect, openApp, test } from "./helpers"

test("Learn: pick a sign, arrows, Show me, Play example grading for a word, a letter and a two-hand word", async ({ page, errors }) => {
  void errors
  await openApp(page, "learn")
  const title = page.getByTestId("learn-title")
  await expect(title).toHaveText("Hello")
  await expect(page.getByRole("img", { name: "Reference hand for Hello" })).toBeVisible()
  await page.getByRole("button", { name: "Next sign" }).click()
  await expect(title).toHaveText("Yes")
  await page.getByRole("button", { name: "Previous sign" }).click()
  await page.getByRole("button", { name: "Previous sign" }).click()
  await expect(title).toHaveText("Letter Y")
  await page.getByRole("button", { name: "Next sign" }).click()
  await expect(title).toHaveText("Hello")
  await page.getByRole("button", { name: "Show me" }).click()

  await page.getByRole("button", { name: "Play example" }).click()
  await expect(page.getByTestId("learn-feedback")).toHaveText("Correct! That was HELLO.")
  await expect(page.getByTestId("learn-score")).toHaveText("Score 1 / 1")

  await page.getByLabel("Sign to practise").selectOption("B")
  await expect(title).toHaveText("Letter B")
  await expect(page.getByTestId("learn-show")).toContainText("Four fingers straight up")
  await expect(page.getByRole("button", { name: "Show me" })).toHaveCount(0)
  await page.getByRole("button", { name: "Play example" }).click()
  await expect(page.getByTestId("learn-feedback")).toHaveText("Correct! That was B.")

  await page.getByLabel("Sign to practise").selectOption("HELP")
  await expect(page.getByText("Two hands").first()).toBeVisible()
  await page.getByRole("button", { name: "Play example" }).click()
  await expect(page.getByTestId("learn-feedback")).toHaveText("Correct! That was HELP.")
  await page.getByLabel("Sign to practise").selectOption("SCHOOL")
  await page.getByRole("button", { name: "Play example" }).click()
  await expect(page.getByTestId("learn-feedback")).toHaveText("Correct! That was SCHOOL.")
  await expect(page.getByTestId("learn-score")).toHaveText("Score 4 / 4")
})

test("Learn: quiz with hint, example, skip, result, play again, end and back", async ({ page, errors }) => {
  void errors
  await openApp(page, "learn")
  await page.getByRole("button", { name: /Start quiz/ }).click()
  const progress = page.getByTestId("quiz-progress")
  await expect(progress).toHaveText("Question 1 of 5")
  await expect(page.getByTestId("learn-title")).toHaveText(/^Sign: /)
  await expect(page.getByRole("img", { name: /Reference hand/ })).toHaveCount(0)
  await page.getByRole("button", { name: "Show hint" }).click()
  await expect(page.getByRole("img", { name: /Reference hand/ })).toBeVisible()
  await page.getByRole("button", { name: "Play example" }).click()
  await expect(page.getByTestId("learn-feedback")).toHaveText(/^Correct!/)
  await expect(progress).toHaveText("Question 2 of 5")
  for (let i = 0; i < 4; i++) await page.getByRole("button", { name: "Skip" }).click()
  await expect(page.getByTestId("quiz-result")).toContainText("Quiz done: 1 of 5 right")
  await page.getByRole("button", { name: "Play again" }).click()
  await expect(progress).toHaveText("Question 1 of 5")
  await page.getByRole("button", { name: "End quiz" }).click()
  await expect(page.getByLabel("Sign to practise")).toBeVisible()
  await page.getByRole("button", { name: /Start quiz/ }).click()
  for (let i = 0; i < 5; i++) await page.getByRole("button", { name: "Skip" }).click()
  await expect(page.getByTestId("quiz-result")).toContainText("0 of 5")
  await page.getByRole("button", { name: "Back to practice" }).click()
  await expect(page.getByLabel("Sign to practise")).toBeVisible()
})

